			<h1 id="titre">VIE A L’ECOLE : TRAVAIL ET REUSSITE AUX ETUDES</h1><hr/>
			<p id="contenu">Le secret de la réussite, c’est de se concentrer corps, âme et esprit, se sacrifier, travailler avec force, courage, amour, intelligence, sagesse, et avec toute énergie de la puissance spirituelle.<br/>
			<div id="p1">Il faut vous sentir libre,</div>
			<div id="p2">A l’aise quand vous étudiez,</div>
			<div id="p3">Dans le cœur rempli de joie,</div>
			<div id="p4">De paix,</div> 
			<div id="p5">De confiance,</div>
			<div id="p6">D’aisance,</div>
			Enfin d’arriver à votre objectif.<br/><br/>Chaque personne est le maître de sa vie. Etudier avec travail, c’est étudier avec la réussite, succès, bonté, et dans la prière, l’humilité, la louange, l’adoration à celui à qui l’humanité doit beaucoup, celui qui a la source de vie, des connaissances et des savoirs : c’est la réussite avec réussite dans les études.<br/><br/>Il faut stabiliser sa pensée en étudiant chaque jour. Il faut avoir l’amour de soi, se donner plus de chance. Dieu nous a donné le pouvoir de dominer le monde, rien dans le monde n’est nous limite.<br/><br/>Concentrez-vous, cultivez votre cerveau <em>aux recherches scientifiques, professionnelles et aux lectures ;</em> stabilisez votre pensée, car nos pensées nous font devenir les êtres humains ; et la richesse est la marque de pensée. Voila, le bonheur de l’intérieur du cœur est le carburant de la réussite.<br/><br/>En effet, on peut parler d’un bon travail lorsque l’élève se donne aux études et qu’il consacre le temps nécessaire à sa réussite. Jusqu’ici la discipline demeure le point de départ de la réussite, l’élève doit nécessairement respecter les autorités scolaires et suivre le règlement d’ordre intérieur de l’école pour qu’il ait une bonne conduite. Et n’oubliez jamais que pour bien réussir vos études, vous devrez travailler dur à l’école et méditer vos leçons chaque jour ; on sait que travail égal réussite  égal salaire; si le travail s’accroit, le rendement aussi augmente et il y a un bon résultat ; donc, il faut travailler fort pour arracher votre réussite par ce qu’elle se mérite.<em>« La réussite aux études est facile à celui qui travaille dur et qui étudie chaque jour ».</em><br/><br/>La vie n’est rien sans l’étude,<br/>L’étude aussi n’est rien sans la vie,<br/>Seules, l’intelligence et la sagesse<br/>Suffisent pour la vie et l’étude.
			</p>
			<p id="Auteur"><strong>Eroish COMBAT-FORT</strong><br/>Elève 6e Math-Physique à IFCEPS du Mont KITENGE<br/>RD Congo, Ville de Kisangani</p>

			
